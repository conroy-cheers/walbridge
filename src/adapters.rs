use crate::palette::{render_template, Palette};
use anyhow::{Context, Result};
use serde::{Deserialize, Serialize};
use std::{
    fs,
    path::{Path, PathBuf},
    process::Command,
};

#[derive(Clone, Copy, Debug, Deserialize, Serialize)]
#[serde(rename_all = "snake_case")]
pub enum ApplyMode {
    Live,
    Restart,
}

#[derive(Debug, Deserialize, Serialize)]
pub struct AdapterStatus {
    pub name: String,
    pub apply_mode: ApplyMode,
    pub success: bool,
    pub paths: Vec<String>,
    pub note: Option<String>,
    pub error: Option<String>,
}

#[derive(Debug)]
pub struct ApplyContext {
    pub home_dir: PathBuf,
    pub config_dir: PathBuf,
    pub data_dir: PathBuf,
    pub gtk_base_theme_name: String,
    pub gtk3_base_css: String,
    pub gtk4_base_css: String,
}

impl ApplyContext {
    pub fn from_env() -> Result<Self> {
        let home_dir = std::env::var_os("HOME")
            .map(PathBuf::from)
            .context("HOME is not set")?;

        let config_dir = std::env::var_os("XDG_CONFIG_HOME")
            .map(PathBuf::from)
            .unwrap_or_else(|| home_dir.join(".config"));
        let data_dir = std::env::var_os("XDG_DATA_HOME")
            .map(PathBuf::from)
            .unwrap_or_else(|| home_dir.join(".local/share"));

        Ok(Self {
            home_dir,
            config_dir,
            data_dir,
            gtk_base_theme_name: std::env::var("WALBRIDGE_GTK_BASE_THEME_NAME")
                .unwrap_or_else(|_| "adw-gtk3-dark".into()),
            gtk3_base_css: std::env::var("WALBRIDGE_GTK3_BASE_CSS").unwrap_or_default(),
            gtk4_base_css: std::env::var("WALBRIDGE_GTK4_BASE_CSS").unwrap_or_default(),
        })
    }
}

pub fn apply_all(ctx: &ApplyContext, palette: &Palette) -> Vec<AdapterStatus> {
    let adapters = [
        (
            "gtk",
            apply_gtk as fn(&ApplyContext, &Palette) -> Result<AdapterStatus>,
        ),
        ("qt", apply_qt),
        ("wezterm", apply_wezterm),
        ("starship", apply_starship),
        ("fish", apply_fish),
        ("atuin", apply_atuin),
        ("ghostty", apply_ghostty),
        ("bat", apply_bat),
        ("vscode", apply_vscode),
        ("btop", apply_btop),
    ];

    adapters
        .into_iter()
        .map(|(name, apply)| match apply(ctx, palette) {
            Ok(status) => status,
            Err(error) => AdapterStatus {
                name: name.to_string(),
                apply_mode: ApplyMode::Restart,
                success: false,
                paths: Vec::new(),
                note: None,
                error: Some(format!("{error:#}")),
            },
        })
        .collect()
}

fn apply_gtk(ctx: &ApplyContext, palette: &Palette) -> Result<AdapterStatus> {
    anyhow::ensure!(
        !ctx.gtk3_base_css.is_empty() && !ctx.gtk4_base_css.is_empty(),
        "missing walbridge GTK base theme paths"
    );
    let gtk4_rendered = render_gtk_theme(
        include_str!("../templates/gtk.css"),
        &ctx.gtk4_base_css,
        &palette.render_context(),
    );
    let gtk3_rendered = render_gtk_theme(
        include_str!("../templates/gtk3.css"),
        &ctx.gtk3_base_css,
        &palette.render_context(),
    );
    let current_theme = current_gtk_theme().ok();
    let next_theme_name = match current_theme.as_deref() {
        Some("WalbridgeA") => "WalbridgeB",
        _ => "WalbridgeA",
    };
    let theme_root = ctx.data_dir.join("themes").join(next_theme_name);
    let gtk3_theme = theme_root.join("gtk-3.0/gtk.css");
    let gtk4_theme = theme_root.join("gtk-4.0/gtk.css");
    let theme_index = theme_root.join("index.theme");
    let gtk3_override = ctx.config_dir.join("gtk-3.0/gtk.css");
    let gtk4_override = ctx.config_dir.join("gtk-4.0/gtk.css");

    write_text(&gtk3_theme, &gtk3_rendered)?;
    write_text(&gtk4_theme, &gtk4_rendered)?;
    write_text(
        &theme_index,
        &format!(
            "[Desktop Entry]\nType=X-GNOME-Metatheme\nName={next_theme_name}\nComment=Generated by walbridge\n\n[X-GNOME-Metatheme]\nGtkTheme={next_theme_name}\nMetacityTheme={base}\nIconTheme=Papirus\nCursorTheme=catppuccin-mocha-lavender-cursors\nButtonLayout=menu:minimize,maximize,close\n",
            base = ctx.gtk_base_theme_name,
        ),
    )?;
    clear_override_css(&gtk3_override)?;
    clear_override_css(&gtk4_override)?;
    set_gtk_theme(next_theme_name)?;

    Ok(AdapterStatus {
        name: "gtk".into(),
        apply_mode: ApplyMode::Live,
        success: true,
        paths: vec![
            gtk3_theme.display().to_string(),
            gtk4_theme.display().to_string(),
            theme_index.display().to_string(),
            gtk3_override.display().to_string(),
            gtk4_override.display().to_string(),
        ],
        note: Some(
            "Generated alternating GTK themes layered on a real base theme and switched `gtk-theme-name` live. Apps that had the old walbridge `gtk.css` override loaded may need one restart to migrate."
                .into(),
        ),
        error: None,
    })
}

fn apply_qt(ctx: &ApplyContext, palette: &Palette) -> Result<AdapterStatus> {
    let qt5_config = ctx.config_dir.join("qt5ct/qt5ct.conf");
    let qt6_config = ctx.config_dir.join("qt6ct/qt6ct.conf");
    let qt5_colors = ctx.config_dir.join("qt5ct/colors/walbridge.conf");
    let qt6_colors = ctx.config_dir.join("qt6ct/colors/walbridge.conf");

    let existing_qt5 = fs::read_to_string(&qt5_config).unwrap_or_default();
    let existing_qt6 = fs::read_to_string(&qt6_config).unwrap_or_default();

    let qt5_style = preferred_qt_style(&existing_qt5);
    let qt6_style = preferred_qt_style(&existing_qt6);
    let qt5_fonts = extract_qt_fonts(&existing_qt5);
    let qt6_fonts = extract_qt_fonts(&existing_qt6);

    write_text(&qt5_colors, &render_qt_colors(palette))?;
    write_text(&qt6_colors, &render_qt_colors(palette))?;
    write_text(
        &qt5_config,
        &render_qtct_config(
            &qt5_colors,
            &qt5_style,
            &qt5_fonts.general,
            &qt5_fonts.fixed,
        ),
    )?;
    write_text(
        &qt6_config,
        &render_qtct_config(
            &qt6_colors,
            &qt6_style,
            &qt6_fonts.general,
            &qt6_fonts.fixed,
        ),
    )?;

    Ok(AdapterStatus {
        name: "qt".into(),
        apply_mode: ApplyMode::Restart,
        success: true,
        paths: vec![
            qt5_config.display().to_string(),
            qt6_config.display().to_string(),
            qt5_colors.display().to_string(),
            qt6_colors.display().to_string(),
        ],
        note: Some("Qt apps usually need reopening to pick up qtct palette changes.".into()),
        error: None,
    })
}

fn apply_vscode(ctx: &ApplyContext, palette: &Palette) -> Result<AdapterStatus> {
    let theme_json = render_template(
        include_str!("../templates/vscode-theme.json"),
        &palette.render_context(),
    );

    let extension_package = r#"{
  "name": "walbridge-pywal-theme",
  "displayName": "Walbridge Pywal Theme",
  "publisher": "walbridge",
  "version": "0.1.0",
  "engines": {
    "vscode": "^1.80.0"
  },
  "categories": [
    "Themes"
  ],
  "contributes": {
    "themes": [
      {
        "label": "Walbridge",
        "uiTheme": "vs-dark",
        "path": "./themes/walbridge-color-theme.json"
      }
    ]
  }
}
"#;

    let roots = [
        ctx.home_dir
            .join(".vscode-oss/extensions/walbridge.theme-pywal"),
        ctx.home_dir
            .join(".vscode/extensions/walbridge.theme-pywal"),
    ];

    let mut paths = Vec::new();
    for root in roots {
        let package_json = root.join("package.json");
        let theme_path = root.join("themes/walbridge-color-theme.json");
        write_text(&package_json, extension_package)?;
        write_text(&theme_path, &theme_json)?;
        paths.push(package_json.display().to_string());
        paths.push(theme_path.display().to_string());
    }

    Ok(AdapterStatus {
        name: "vscode".into(),
        apply_mode: ApplyMode::Restart,
        success: true,
        paths,
        note: Some("VS Code and VSCodium need reopening to pick up updated theme files.".into()),
        error: None,
    })
}

