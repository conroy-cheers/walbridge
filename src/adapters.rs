fn apply_starship(ctx: &ApplyContext, palette: &Palette) -> Result<AdapterStatus> {
    let template_path = ctx.config_dir.join("starship.toml");
    let target_path = ctx.config_dir.join("starship-walbridge.toml");
    let template = fs::read_to_string(&template_path).with_context(|| {
        format!(
            "failed to read starship template `{}`",
            template_path.display()
        )
    })?;
    let rendered = render_starship_config(&template, palette);
    write_text(&target_path, &rendered)?;

    Ok(AdapterStatus {
        name: "starship".into(),
        apply_mode: ApplyMode::Live,
        success: true,
        paths: vec![target_path.display().to_string()],
        note: Some(
            "Generated `starship-walbridge.toml` from the static Starship template. New prompts use it immediately."
                .into(),
        ),
        error: None,
    })
}

