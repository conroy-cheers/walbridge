fn apply_bat(ctx: &ApplyContext, palette: &Palette) -> Result<AdapterStatus> {
    let theme = render_template(
        include_str!("../templates/bat.tmTheme"),
        &palette.render_context(),
    );
    let theme_path = ctx.config_dir.join("bat/themes/walbridge.tmTheme");
    write_text(&theme_path, &theme)?;

    let status = Command::new("bat")
        .args(["cache", "--build"])
        .status()
        .context("failed to run `bat cache --build`")?;
    anyhow::ensure!(status.success(), "`bat cache --build` exited with {status}");

    Ok(AdapterStatus {
        name: "bat".into(),
        apply_mode: ApplyMode::Live,
        success: true,
        paths: vec![theme_path.display().to_string()],
        note: Some(
            "Generated the runtime bat theme `walbridge` and rebuilt bat's theme cache. New bat invocations will use it immediately."
                .into(),
        ),
        error: None,
    })
}

